function interactions = interaction()
%INTERACTION Define the three non-matching interfaces in the four-domain chain.
%
% Each endpoint selects a geometric boundary, one column of pdemodel.fint,
% and the local solution component exchanged with the neighboring domain.
%
% pdemodel.fint column 1: -uhat, used to impose solution continuity.
% pdemodel.fint column 2: numerical normal flux, used to impose flux balance.

% Interaction 1 couples domain 1's right boundary to domain 2's left boundary.
interactions(1) = struct( ...
    'domains',    [1,2], ...
    'type',       1, ...
    'interface1', 2, ...
    'condition1', 1, ...
    'fluxmap1',   1, ...
    'interface2', 4, ...
    'condition2', 2, ...
    'fluxmap2',   1);

% Interaction 2 couples domain 2's right boundary to domain 3's left boundary.
interactions(2) = struct( ...
    'domains',    [2,3], ...
    'type',       1, ...
    'interface1', 2, ...
    'condition1', 2, ...
    'fluxmap1',   1, ...
    'interface2', 4, ...
    'condition2', 1, ...
    'fluxmap2',   1);

% Interaction 3 couples domain 3's right boundary to domain 4's left boundary.
interactions(3) = struct( ...
    'domains',    [3,4], ...
    'type',       1, ...
    'interface1', 2, ...
    'condition1', 1, ...
    'fluxmap1',   1, ...
    'interface2', 4, ...
    'condition2', 2, ...
    'fluxmap2',   1);
end
