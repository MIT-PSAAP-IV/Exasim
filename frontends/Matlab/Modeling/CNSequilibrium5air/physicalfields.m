function fields = physicalfields(UDG, db, rhoRef, eRef, uRef)
rho = UDG(:,1,:);
ux = UDG(:,2,:)./rho;
uy = UDG(:,3,:)./rho;
e = UDG(:,4,:)./rho - 0.5*(ux.^2 + uy.^2);
rhoPhys = rhoRef*rho;
ePhys = eRef*e;
xi = log(rhoPhys);
props = local_interp_database(db, xi(:), ePhys(:));
p = reshape(props(:,1), size(rho));
T = reshape(props(:,2), size(rho));
a = reshape(props(:,6), size(rho));
velocityPhys = sqrt(ux.^2 + uy.^2)*uRef;
Mach = velocityPhys./a;
Ysum = sum(props(:,11:15),2);
fields = struct();
fields.xiRange = [min(xi(:)), max(xi(:))];
fields.rhoRange = exp(fields.xiRange);
fields.eRange = [min(ePhys(:)), max(ePhys(:))];
fields.pRange = [min(p(:)), max(p(:))];
fields.TRange = [min(T(:)), max(T(:))];
fields.velocityRange = [min(velocityPhys(:)), max(velocityPhys(:))];
fields.MachRange = [min(Mach(:)), max(Mach(:))];
fields.speciesMassFractionRanges = reshape([min(props(:,11:15),[],1); max(props(:,11:15),[],1)], [2,5]);
fields.YsumErrorMax = max(abs(Ysum - 1));
fields.tableMargin = min([fields.xiRange(1)-db.xi(1), db.xi(end)-fields.xiRange(2), ...
                          fields.eRange(1)-db.e(1), db.e(end)-fields.eRange(2)]);
fields.outsideTable = fields.tableMargin < 0;
fields.rhoField = rhoPhys;
fields.pressureField = p;
fields.temperatureField = T;
fields.velocityField = velocityPhys;
fields.energydensityField = rhoPhys.*(ePhys + 0.5*velocityPhys.^2);
fields.MachField = Mach;
fields.YN2 = reshape(props(:,11), size(rho));
fields.YO2 = reshape(props(:,12), size(rho));
fields.YNO = reshape(props(:,13), size(rho));
fields.YN = reshape(props(:,14), size(rho));
fields.YO = reshape(props(:,15), size(rho));
end
